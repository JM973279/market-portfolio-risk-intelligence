// Regression checks for the existing operational/OOS display boundary.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const source = fs.readFileSync('src/lib/operational-status.ts', 'utf8');
const code = ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const moduleValue = {exports:{}};
vm.runInNewContext(code, {module:moduleValue,exports:moduleValue.exports});
const {currentOperationalPoint, latestOperationalPoint, operationalChartPoints, operationalMessage} = moduleValue.exports;
const data = JSON.parse(fs.readFileSync('public/data/operational-markets.json', 'utf8'));
const kr = data.markets.korea, us = data.markets.us;
assert.equal(currentOperationalPoint(kr).date, '2026-11-02');
assert.equal((currentOperationalPoint(kr).risk * 100).toFixed(1), '40.2');
assert.equal(currentOperationalPoint(kr).msi.toFixed(3), '0.753');
assert.equal(currentOperationalPoint(kr).threshold.toFixed(3), '1.115');
assert.ok(!operationalMessage(kr, 'ko').includes('없습니다'));
assert.ok(operationalMessage(kr, 'en').includes('verified'));
assert.equal(currentOperationalPoint(us), null);
assert.equal(us.dataPolicy, 'us-full-source-vintage-v1');
assert.ok(latestOperationalPoint(us));
assert.equal(latestOperationalPoint(us).date, us.lastValid.date);
assert.ok(us.lastValid.date < us.expectedDate);
assert.ok(operationalMessage(us, 'en').includes('Verified inference'));
assert.ok(!/[가-힣]/.test(operationalMessage(us, 'en')));
const blocked = {...us, status:'BLOCKED', current:null, lastValid:{...us.lastValid,recordType:'RETROSPECTIVE_INFERENCE'}};
assert.equal(latestOperationalPoint(blocked), null);
assert.ok(operationalMessage(blocked, 'en').includes('withheld'));
assert.equal(latestOperationalPoint({...us,baselineParity:false}),null);
assert.equal(latestOperationalPoint({...us,status:'CURRENT',expectedDate:us.lastValid.date,current:us.lastValid,baselineParity:false}),null);
assert.equal(latestOperationalPoint({...us,inferenceSucceeded:false}),null);
assert.equal(latestOperationalPoint({...us,lastValid:{...us.lastValid,recordType:'RETROSPECTIVE_INFERENCE'}}),null);
assert.equal(latestOperationalPoint({...us,availability:[]}),null);
assert.equal(latestOperationalPoint({...us,series:us.series.filter(s=>s.name!=='DBAA')}),null);
for (const risk of [NaN,Infinity,-0.1,1.1,null]) assert.equal(latestOperationalPoint({...us,lastValid:{...us.lastValid,risk}}),null);
const chart = operationalChartPoints(us);
assert.ok(chart.length > 200);
assert.equal(chart.at(-1).date, us.priceHistory.at(-1).date);
assert.ok(chart.at(-1).price > 0);
assert.equal(chart.at(-1).risk, null); // prices do not carry a Friday score into Monday
assert.equal(chart.find(p=>p.date===us.lastValid.date).risk,us.lastValid.risk);
assert.ok(operationalChartPoints(blocked).every(p=>p.risk===null));
assert.ok(operationalChartPoints({...us,history:us.history.map(p=>({...p,recordType:'RETROSPECTIVE_INFERENCE'}))}).every(p=>p.risk===null));
assert.equal(currentOperationalPoint({...us, current:us.lastValid}), null);
assert.equal(currentOperationalPoint({...kr, current:{...kr.current,date:'2026-11-01'}}), null);
for (const risk of [NaN,Infinity,-0.1,1.1,null]) assert.equal(currentOperationalPoint({...kr,current:{...kr.current,risk}}),null);
assert.equal(currentOperationalPoint({...kr,current:{...kr.current,msi:null}}),null);
assert.equal(currentOperationalPoint({...kr,current:null}),null);
assert.equal(currentOperationalPoint(null),null);
assert.ok(operationalMessage(null, 'en').includes('No operational export'));
const historical = JSON.parse(fs.readFileSync('public/data/global-markets.json', 'utf8'));
assert.equal(historical.korea.filter(p=>p.risk!==null).at(-1).date,'2026-09-16');
assert.equal(historical.us.filter(p=>p.risk!==null).at(-1).date,'2026-09-21');
console.log('PASS: latest verified US observation, independent current price, missing-input gaps, blocked/cache separation, Korean snapshot and preserved OOS dates');
